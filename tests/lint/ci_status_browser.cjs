const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const number = process.env.PROOF_PR;
  if (!/^[1-9][0-9]*$/.test(number)) throw new Error('Invalid PR number');
  fs.mkdirSync('ci-display-proof', {recursive: true});
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1200}});
  await page.goto(`https://github.com/luohuan19/pypto/pull/${number}`, {waitUntil: 'domcontentloaded'});
  await page.locator('details.commit-build-statuses').last().locator('summary').click();
  await page.getByText('full / unit-tests (ubuntu-latest, 3.10)', {exact: true}).waitFor({state: 'visible'});
  await page.waitForTimeout(2000);
  fs.writeFileSync('ci-display-proof/pr.html', await page.content());
  fs.writeFileSync('ci-display-proof/pr.txt', await page.locator('body').innerText());
  await page.screenshot({path: 'ci-display-proof/pr.png', fullPage: true});
  const links = await page.locator('a').evaluateAll(as => as.map(a => ({text: a.textContent.trim(), href: a.href})).filter(a => a.href.includes('/actions/runs/') || a.text.includes('full /')));
  console.log(JSON.stringify(links));
  fs.writeFileSync('ci-display-proof/links.json', JSON.stringify(links, null, 2));
  const source = links.find(a => a.href.includes('/actions/runs/43139855844/job/'));
  if (!source) throw new Error('The PR status popup did not expose an original job link');
  await page.goto(source.href, {waitUntil: 'domcontentloaded'});
  fs.writeFileSync('ci-display-proof/job-link.json', JSON.stringify({requested: source.href, landed: page.url(), title: await page.title()}, null, 2));
  if (page.url() !== source.href) throw new Error('Job link did not preserve the original target');
  await page.screenshot({path: 'ci-display-proof/job.png', fullPage: true});
  await browser.close();
})();
